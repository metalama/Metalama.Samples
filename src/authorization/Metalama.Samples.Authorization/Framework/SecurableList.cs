using System.Collections.ObjectModel;
using System.Diagnostics.CodeAnalysis;

namespace Metalama.Samples.Authorization;

/// <summary>
/// A list that belongs to a securable object. Once it has an owner, each change demands the write permission of
/// the property on the owner, then calls the owner (see <see cref="ISecurableCollectionOwner"/>). Reading the list
/// checks nothing: the getter of the property has already checked the read permission.
/// </summary>
/// <remarks>
/// <para>The developer initializes the property with a securable list, for instance
/// <c>public IList&lt;InvoiceLine&gt; Lines { get; } = new SecurableList&lt;InvoiceLine&gt;();</c>. A property
/// initializer runs where the owner is not available, so the list starts without an owner. The getter generated by
/// <see cref="RequiresPermissionAttribute"/> sets the owner on the first access, and the owner can be set only once.</para>
/// <para>A list without an owner is not checked. Only the code of the owner can reach it before the first access, and
/// so can Entity Framework, which fills the list when it loads the object.</para>
/// </remarks>
// The list is securable: a member of this type protects itself. Its own members are not secured, because each
// change is checked against the owner of the list, not against the list.
[AuthorizationOptions( IsDefaultSecuringEnabled = false )]
public sealed class SecurableList<T> : Collection<T>, ISecurableCollection, ISecurable
{
    private string? _writePermission;
    private string? _member;
    private string? _propertyName;

    public SecurableList() { }

    public SecurableList( IEnumerable<T> items ) : base( [.. items] ) { }

    /// <summary>
    /// Gets the object that owns the list, or <c>null</c> before the first access through the property.
    /// </summary>
    public ISecurable? Owner { get; private set; }

    /// <inheritdoc />
    public void SetOwner( ISecurable owner, string writePermission, string member, string propertyName )
    {
        if ( this.Owner == null )
        {
            this.Owner = owner;
            this._writePermission = writePermission;
            this._member = member;
            this._propertyName = propertyName;
        }
        else if ( !ReferenceEquals( this.Owner, owner ) )
        {
            // Sharing a list between two objects would check the permission on the wrong one.
            throw new InvalidOperationException( $"The list of {member} already belongs to another object." );
        }
    }

    protected override void InsertItem( int index, T item )
    {
        this.OnChanging( AccessKind.Add );
        base.InsertItem( index, item );
    }

    protected override void SetItem( int index, T item )
    {
        this.OnChanging( AccessKind.Replace );
        base.SetItem( index, item );
    }

    protected override void RemoveItem( int index )
    {
        this.OnChanging( AccessKind.Remove );
        base.RemoveItem( index );
    }

    protected override void ClearItems()
    {
        this.OnChanging( AccessKind.Remove );
        base.ClearItems();
    }

    // The permission comes first: the owner validates its business rules only for authorized changes.
    private void OnChanging( AccessKind accessKind )
    {
        if ( this.Owner == null )
        {
            return;
        }

        AccessGuard.Demand( this.Owner, this._writePermission!, this._member!, accessKind );

        if ( this.Owner is ISecurableCollectionOwner owner )
        {
            owner.OnCollectionChanging( this._propertyName!, accessKind );
        }
    }
}

/// <summary>
/// A collection that checks its changes against the permissions of its owner. See <see cref="SecurableList{T}"/>.
/// </summary>
public interface ISecurableCollection
{
    /// <summary>
    /// Sets the owner of the collection and the permission required to change it. The owner can be set only once;
    /// setting the same owner again has no effect.
    /// </summary>
    void SetOwner( ISecurable owner, string writePermission, string member, string propertyName );
}

/// <summary>
/// Implemented by an object that validates the changes of its securable collections, for instance to enforce a
/// business rule such as "only a draft invoice can be edited".
/// </summary>
public interface ISecurableCollectionOwner
{
    /// <summary>
    /// Called before a change of a securable collection, after the permission has been checked. Throw to cancel
    /// the change.
    /// </summary>
    /// <param name="propertyName">The name of the property whose collection changes.</param>
    /// <param name="accessKind">The kind of change: <see cref="AccessKind.Add"/>, <see cref="AccessKind.Remove"/>
    /// or <see cref="AccessKind.Replace"/>.</param>
    void OnCollectionChanging( string propertyName, AccessKind accessKind );
}

/// <summary>
/// The code generated by <see cref="RequiresPermissionAttribute"/> calls these methods in the getter of a collection
/// property. The C# compiler chooses the overload from the type of the property and infers the item type.
/// </summary>
/// <remarks>
/// <para>A securable collection gets its owner on the first access. A mutable collection that is not securable, such as a
/// <see cref="List{T}"/> or an array, makes the getter throw: returning it would let any reader change the state of
/// the owner. Any other value, such as an immutable collection or a LINQ query, is returned as it is.</para>
/// </remarks>
public static class SecurableCollection
{
    // A property declared with a securable type, such as SecurableList<T>, keeps its type.
    [return: NotNullIfNotNull( nameof(collection) )]
    public static TCollection? SetOwner<TCollection>( TCollection? collection, ISecurable owner, string writePermission, string member, string propertyName )
        where TCollection : class, ISecurableCollection
    {
        collection?.SetOwner( owner, writePermission, member, propertyName );

        return collection;
    }

    [return: NotNullIfNotNull( nameof(items) )]
    public static IList<T>? SetOwner<T>( IList<T>? items, ISecurable owner, string writePermission, string member, string propertyName )
        => Check<IList<T>, T>( items, owner, writePermission, member, propertyName );

    [return: NotNullIfNotNull( nameof(items) )]
    public static ICollection<T>? SetOwner<T>( ICollection<T>? items, ISecurable owner, string writePermission, string member, string propertyName )
        => Check<ICollection<T>, T>( items, owner, writePermission, member, propertyName );

    [return: NotNullIfNotNull( nameof(items) )]
    public static IReadOnlyList<T>? SetOwner<T>( IReadOnlyList<T>? items, ISecurable owner, string writePermission, string member, string propertyName )
        => Check<IReadOnlyList<T>, T>( items, owner, writePermission, member, propertyName );

    [return: NotNullIfNotNull( nameof(items) )]
    public static IReadOnlyCollection<T>? SetOwner<T>(
        IReadOnlyCollection<T>? items,
        ISecurable owner,
        string writePermission,
        string member,
        string propertyName )
        => Check<IReadOnlyCollection<T>, T>( items, owner, writePermission, member, propertyName );

    [return: NotNullIfNotNull( nameof(items) )]
    public static IEnumerable<T>? SetOwner<T>( IEnumerable<T>? items, ISecurable owner, string writePermission, string member, string propertyName )
        => Check<IEnumerable<T>, T>( items, owner, writePermission, member, propertyName );

    private static TCollection? Check<TCollection, T>(
        TCollection? items,
        ISecurable owner,
        string writePermission,
        string member,
        string propertyName )
        where TCollection : class, IEnumerable<T>
    {
        switch ( items )
        {
            case null:
                return null;

            case ISecurableCollection securableCollection:
                securableCollection.SetOwner( owner, writePermission, member, propertyName );

                return items;

            // An array is fixed-size, so it reports IsReadOnly, but its items can be replaced.
            case T[]:
            case ICollection<T> { IsReadOnly: false }:
                // Fail closed: a secured property must not return a mutable collection that checks nothing.
                throw new InvalidOperationException(
                    $"{member} returns a mutable {items.GetType().Name}. Initialize it with a {nameof(SecurableList<T>)}<T>." );

            default:
                return items;
        }
    }
}
