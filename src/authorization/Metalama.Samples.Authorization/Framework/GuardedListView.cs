using System.Collections;
using System.Diagnostics.CodeAnalysis;

namespace Metalama.Samples.Authorization;

/// <summary>
/// A view of a list owned by a securable object: reading the list is free, and each change demands a permission
/// on the owner. <see cref="RequiresPermissionAttribute"/> returns this view from the getter of a property of type
/// <see cref="IList{T}"/> or <see cref="ICollection{T}"/>, so that a caller who may only read the property cannot
/// change its content.
/// </summary>
/// <remarks>
/// The getter has already checked the read permission, so reading the list through the view checks nothing more.
/// The view holds a reference to the owner, not a copy of the list: changes are made to the list of the owner.
/// </remarks>
public sealed class GuardedListView<T> : IList<T>, IReadOnlyList<T>
{
    private readonly IList<T> _list;
    private readonly object _owner;
    private readonly string _writePermission;
    private readonly string _member;

    public GuardedListView( IList<T> list, object owner, string writePermission, string member )
    {
        this._list = list;
        this._owner = owner;
        this._writePermission = writePermission;
        this._member = member;
    }

    public int Count => this._list.Count;

    public bool IsReadOnly => this._list.IsReadOnly;

    public T this[ int index ]
    {
        get => this._list[index];
        set
        {
            this.DemandWrite();
            this._list[index] = value;
        }
    }

    public void Add( T item )
    {
        this.DemandWrite();
        this._list.Add( item );
    }

    public void Insert( int index, T item )
    {
        this.DemandWrite();
        this._list.Insert( index, item );
    }

    public bool Remove( T item )
    {
        this.DemandWrite();

        return this._list.Remove( item );
    }

    public void RemoveAt( int index )
    {
        this.DemandWrite();
        this._list.RemoveAt( index );
    }

    public void Clear()
    {
        this.DemandWrite();
        this._list.Clear();
    }

    public bool Contains( T item ) => this._list.Contains( item );

    public int IndexOf( T item ) => this._list.IndexOf( item );

    public void CopyTo( T[] array, int arrayIndex ) => this._list.CopyTo( array, arrayIndex );

    public IEnumerator<T> GetEnumerator() => this._list.GetEnumerator();

    IEnumerator IEnumerable.GetEnumerator() => this.GetEnumerator();

    private void DemandWrite() => AccessGuard.Demand( this._owner, this._writePermission, this._member, AccessKind.Write );
}

/// <summary>
/// Creates <see cref="GuardedListView{T}"/> views. The code generated by <see cref="RequiresPermissionAttribute"/>
/// calls these methods, and the C# compiler infers the item type.
/// </summary>
public static class GuardedCollection
{
    [return: NotNullIfNotNull( nameof(list) )]
    public static IList<T>? Wrap<T>( IList<T>? list, object owner, string writePermission, string member )
        => list == null ? null : new GuardedListView<T>( list, owner, writePermission, member );

    [return: NotNullIfNotNull( nameof(collection) )]
    public static ICollection<T>? Wrap<T>( ICollection<T>? collection, object owner, string writePermission, string member )
        => collection switch
        {
            null => null,
            IList<T> list => new GuardedListView<T>( list, owner, writePermission, member ),

            // The view protects lists only. A property declared as ICollection<T> must return a list.
            _ => throw new NotSupportedException( $"{member} must return an {nameof(IList<T>)} to be secured." )
        };
}
