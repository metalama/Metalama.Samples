using System.Collections.Immutable;

namespace Metalama.Samples.Authorization;

/// <summary>
/// Gives access to the current <see cref="ISecurityContext"/>. The context, its permission grants and the system
/// scope flow with the logical call (<see cref="AsyncLocal{T}"/>), so they follow <c>async</c> code and stay
/// isolated between concurrent operations.
/// </summary>
/// <remarks>
/// <para>The framework enforces authorization inside a process against missing checks. It is not a sandbox: any
/// code of the process can call <see cref="Use"/>, <see cref="Grant"/> or <see cref="RunAsSystem"/>. Only trusted
/// infrastructure, such as an authentication middleware or a database seeder, and the code generated by
/// <see cref="GrantsPermissionsAttribute"/> should call them.</para>
/// <para>A context, a grant or a system scope also applies to the tasks started while it is active, because
/// <see cref="AsyncLocal{T}"/> values flow into them.</para>
/// </remarks>
public static class SecurityContext
{
    // The grants belong to the context: when the context changes, the grants of the previous subject do not apply.
    private static readonly AsyncLocal<Frame?> _current = new();
    private static readonly AsyncLocal<bool> _isSystem = new();

    /// <summary>
    /// Gets the current security context. When it is <c>null</c>, every secured operation fails,
    /// except in a system scope. Set it with <see cref="Use"/>.
    /// </summary>
    public static ISecurityContext? Current => _current.Value?.Context;

    /// <summary>
    /// Gets a value indicating whether the code runs in a system scope, where no permission is checked.
    /// </summary>
    public static bool IsSystem => _isSystem.Value;

    /// <summary>
    /// Sets <see cref="Current"/> until the returned object is disposed, then restores the previous context.
    /// The grants of the previous context do not apply to the new one.
    /// </summary>
    public static IDisposable Use( ISecurityContext? context )
        => Push( new Frame( context, ImmutableStack<PermissionGrant>.Empty ) );

    /// <summary>
    /// Grants permissions on one object to the current subject until the returned object is disposed. The grant
    /// applies to <paramref name="securable"/> only, and only in the current context.
    /// </summary>
    /// <remarks>
    /// The code generated by <see cref="GrantsPermissionsAttribute"/> calls this method after the permission check
    /// of the member. A grant takes precedence over the policy, including its denials.
    /// </remarks>
    /// <param name="securable">The object on which the permissions are granted. When it is <c>null</c>, for instance a
    /// null argument, nothing is granted.</param>
    /// <param name="permissions">The names of the granted permissions.</param>
    public static IDisposable Grant( ISecurable? securable, params string[] permissions )
    {
        if ( securable == null )
        {
            return new Scope( () => { } );
        }

        var frame = _current.Value ?? new Frame( null, ImmutableStack<PermissionGrant>.Empty );

        return Push( frame with { Grants = frame.Grants.Push( new PermissionGrant( securable, permissions ) ) } );
    }

    /// <summary>
    /// Disables permission checks until the returned object is disposed. Use it for trusted code such as
    /// seeding a database. The framework also uses it while a policy runs.
    /// </summary>
    public static IDisposable RunAsSystem()
    {
        var previous = _isSystem.Value;
        _isSystem.Value = true;

        return new Scope( () => _isSystem.Value = previous );
    }

    // Grants are few and short-lived, so a linear search is enough. The stack is immutable: a nested grant creates a
    // new frame that shares the outer grants, and disposing it restores the previous frame.
    internal static bool IsGranted( ISecurable securable, string permission )
    {
        foreach ( var grant in _current.Value?.Grants ?? ImmutableStack<PermissionGrant>.Empty )
        {
            if ( ReferenceEquals( grant.Securable, securable ) && grant.Permissions.Contains( permission ) )
            {
                return true;
            }
        }

        return false;
    }

    private static IDisposable Push( Frame frame )
    {
        var previous = _current.Value;
        _current.Value = frame;

        return new Scope( () => _current.Value = previous );
    }

    private sealed record Frame( ISecurityContext? Context, ImmutableStack<PermissionGrant> Grants );

    private sealed record PermissionGrant( ISecurable Securable, string[] Permissions );

    private sealed class Scope( Action restore ) : IDisposable
    {
        private Action? _restore = restore;

        public void Dispose()
        {
            this._restore?.Invoke();
            this._restore = null;
        }
    }
}
