using System.Collections.Immutable;

namespace Metalama.Samples.Authorization;

/// <summary>
/// Gives access to the current <see cref="ISecurityContext"/>. The context, its permission grants, its cache of
/// decisions, the objects being initialized and the system scope flow with the logical call
/// (<see cref="AsyncLocal{T}"/>), so they follow <c>async</c> code and stay isolated between concurrent operations.
/// </summary>
/// <remarks>
/// <para>The framework enforces authorization inside a process against missing checks. It is not a sandbox: any
/// code of the process can call <see cref="Use"/>, <see cref="Grant"/> or <see cref="RunAsSystem"/>. Only trusted
/// infrastructure, such as an authentication middleware or a database seeder, and the code generated by the
/// aspects should call them.</para>
/// <para>A context, a grant or a system scope also applies to the tasks started while it is active, because
/// <see cref="AsyncLocal{T}"/> values flow into them.</para>
/// <para>Each execution context caches the decisions of the policy, by object and permission. <see cref="Use"/>
/// starts an execution context, and so does <see cref="Grant"/>, which breaks the execution context of its caller.
/// All the code that runs in an execution context, including the methods that it calls and the tasks that it starts,
/// shares its cache. The cache is cleared only after an access that changes the rights, see
/// <see cref="ClearCachedDecisions"/>. Other changes of the rights apply to the execution contexts that start after
/// them.</para>
/// </remarks>
public static class SecurityContext
{
    private static readonly ImmutableDictionary<ISecurable, ImmutableList<Permission>> _noGrants =
        ImmutableDictionary.Create<ISecurable, ImmutableList<Permission>>( ReferenceEqualityComparer.Instance );

    private static readonly ImmutableDictionary<ISecurable, ImmutableList<(Permission Permission, bool IsGranted)>> _emptyCache =
        ImmutableDictionary.Create<ISecurable, ImmutableList<(Permission Permission, bool IsGranted)>>( ReferenceEqualityComparer.Instance );

    private static readonly ImmutableHashSet<ISecurable> _noObjects = ImmutableHashSet.Create<ISecurable>( ReferenceEqualityComparer.Instance );

    // The grants and the cache belong to the execution context: when the context changes, they do not apply.
    private static readonly AsyncLocal<ExecutionContext?> _current = new();
    private static readonly AsyncLocal<bool> _isSystem = new();

    /// <summary>
    /// Gets the current security context. When it is <c>null</c>, every secured operation fails,
    /// except in a system scope. Set it with <see cref="Use"/>.
    /// </summary>
    public static ISecurityContext? Current => _current.Value?.Context;

    /// <summary>
    /// Gets a value indicating whether the code runs in a system scope, where no permission is checked.
    /// </summary>
    public static bool IsSystem => _isSystem.Value;

    /// <summary>
    /// Sets <see cref="Current"/> until the returned scope is disposed, then restores the previous context.
    /// The new execution context starts with an empty cache, and the grants of the previous context do not apply to it.
    /// </summary>
    /// <remarks>
    /// Switching to a subject ends a system scope until the returned scope is disposed: the code then runs with the
    /// permissions of the subject, and the system scope is restored after it.
    /// </remarks>
    public static SecurityScope Use( ISecurityContext? context )
    {
        var previous = _current.Value;
        var previousIsSystem = _isSystem.Value;

        _current.Value = new ExecutionContext( context, _noGrants, previous, sharesInitialization: false );
        _isSystem.Value = false;

        return new SecurityScope( previous, previousIsSystem );
    }

    /// <summary>
    /// Grants permissions on one object to the current subject until the returned scope is disposed. The grant
    /// applies to <paramref name="securable"/> only, and only in the current context.
    /// </summary>
    /// <remarks>
    /// <para>The code generated by <see cref="GrantsPermissionsAttribute"/> calls this method after the permission
    /// check of the member. A grant takes precedence over the policy, including its denials.</para>
    /// <para>A grant breaks the execution context: it starts a child execution context with an empty cache, because
    /// the decisions cached by the parent do not take the grant into account. When the grant ends, the parent execution
    /// context is restored, without the decisions of the child, which took the grant into account.</para>
    /// </remarks>
    /// <param name="securable">The object on which the permissions are granted. When it is <c>null</c>, for instance a
    /// null argument, nothing is granted.</param>
    /// <param name="permissions">The names of the granted permissions.</param>
    public static SecurityScope Grant( ISecurable? securable, params string[] permissions )
    {
        if ( securable == null )
        {
            return default;
        }

        var parent = _current.Value;
        var grants = parent?.Grants ?? _noGrants;
        var granted = grants.GetValueOrDefault( securable, ImmutableList<Permission>.Empty );

        foreach ( var permission in permissions )
        {
            granted = granted.Add( permission );
        }

        _current.Value = new ExecutionContext( parent?.Context, grants.SetItem( securable, granted ), parent, sharesInitialization: true );

        return new SecurityScope( parent );
    }

    /// <summary>
    /// Disables permission checks until the returned scope is disposed. Use it for trusted code such as
    /// seeding a database. The framework also uses it while a policy runs.
    /// </summary>
    public static SecurityScope RunAsSystem()
    {
        var previous = _isSystem.Value;
        _isSystem.Value = true;

        return new SecurityScope( previous );
    }

    /// <summary>
    /// Starts the initialization of an object: until <see cref="EndInitialization"/>, the accesses to the members of
    /// this object are not checked in the current execution context. The code generated by
    /// <see cref="SecurableTypeAttribute"/> calls this method before the code of the constructors.
    /// </summary>
    /// <remarks>
    /// <para>The caller creates the object, so it may set up the object with unlimited rights: the object is not
    /// visible to any other code before its construction ends. The accesses to other objects are checked as usual.</para>
    /// <para>Nothing is recorded in a system scope, where nothing is checked anyway, or without an execution context,
    /// where every check fails. A missing call to <see cref="EndInitialization"/> lasts at most until the current
    /// execution context ends.</para>
    /// </remarks>
    public static void BeginInitialization( ISecurable securable )
    {
        if ( !_isSystem.Value )
        {
            _current.Value?.BeginInitialization( securable );
        }
    }

    /// <summary>
    /// Ends the initialization of an object, after its constructors and its object initializer. The code generated by
    /// <see cref="SecurableTypeAttribute"/> calls this method from the <c>Initialize</c> method, which the call sites
    /// of the constructors call after the object initializer.
    /// </summary>
    public static void EndInitialization( ISecurable securable )
    {
        for ( var context = _current.Value; context != null; context = context.Parent )
        {
            context.EndInitialization( securable );
        }
    }

    /// <summary>
    /// Clears the cached decisions of the current execution context and of the execution contexts that contain it.
    /// <see cref="AccessGuard"/> calls this method after an access that changes the rights, such as a change of the
    /// owner or of the role assignments, so that the next checks of the current operation see the change.
    /// </summary>
    public static void ClearCachedDecisions()
    {
        for ( var context = _current.Value; context != null; context = context.Parent )
        {
            context.ClearCache();
        }
    }

    internal static bool IsInitializing( ISecurable securable )
    {
        for ( var context = _current.Value; context != null; context = context.SharesInitialization ? context.Parent : null )
        {
            if ( context.Initializing.Contains( securable ) )
            {
                return true;
            }
        }

        return false;
    }

    internal static bool IsGranted( ISecurable securable, Permission permission )
        => _current.Value?.Grants.TryGetValue( securable, out var granted ) == true && granted.Contains( permission );

    internal static bool TryGetCachedDecision( ISecurable securable, Permission permission, out bool isGranted )
    {
        if ( _current.Value?.Cache.TryGetValue( securable, out var decisions ) == true )
        {
            foreach ( var decision in decisions )
            {
                if ( decision.Permission == permission )
                {
                    isGranted = decision.IsGranted;

                    return true;
                }
            }
        }

        isGranted = false;

        return false;
    }

    internal static void CacheDecision( ISecurable securable, Permission permission, bool isGranted )
        => _current.Value?.CacheDecision( securable, permission, isGranted );

    internal static void Restore( ExecutionContext? context ) => _current.Value = context;

    internal static void RestoreIsSystem( bool isSystem ) => _isSystem.Value = isSystem;

    /// <summary>
    /// An execution context: the security context, the grants, the cache of decisions and the objects being
    /// initialized. The object is shared by all the code that runs in the execution context, including the
    /// continuations of <c>async</c> methods and the tasks that it starts, so a decision cached by a method that has
    /// returned is visible to its caller. The grants never change. The cache and the objects being initialized are
    /// immutable collections, which a change replaces atomically, so that concurrent tasks can change them without a
    /// lock.
    /// </summary>
    internal sealed class ExecutionContext(
        ISecurityContext? context,
        ImmutableDictionary<ISecurable, ImmutableList<Permission>> grants,
        ExecutionContext? parent,
        bool sharesInitialization )
    {
        private ImmutableDictionary<ISecurable, ImmutableList<(Permission Permission, bool IsGranted)>> _cache = _emptyCache;
        private ImmutableHashSet<ISecurable> _initializing = _noObjects;

        public ISecurityContext? Context { get; } = context;

        public ImmutableDictionary<ISecurable, ImmutableList<Permission>> Grants { get; } = grants;

        /// <summary>
        /// Gets the execution context that was current when this one started.
        /// </summary>
        public ExecutionContext? Parent { get; } = parent;

        /// <summary>
        /// Gets a value indicating whether the objects being initialized in the parent are also being initialized in
        /// this execution context. It is <c>true</c> for a grant, which keeps the subject, and <c>false</c> for
        /// <see cref="Use"/>, which changes it.
        /// </summary>
        public bool SharesInitialization { get; } = sharesInitialization;

        public ImmutableDictionary<ISecurable, ImmutableList<(Permission Permission, bool IsGranted)>> Cache => Volatile.Read( ref this._cache );

        public ImmutableHashSet<ISecurable> Initializing => Volatile.Read( ref this._initializing );

        public void CacheDecision( ISecurable securable, Permission permission, bool isGranted )
            => ImmutableInterlocked.AddOrUpdate(
                ref this._cache,
                securable,
                _ => ImmutableList.Create( (permission, isGranted) ),
                ( _, decisions ) => decisions.Add( (permission, isGranted) ) );

        public void ClearCache() => Volatile.Write( ref this._cache, _emptyCache );

        public void BeginInitialization( ISecurable securable ) => ImmutableInterlocked.Update( ref this._initializing, set => set.Add( securable ) );

        public void EndInitialization( ISecurable securable ) => ImmutableInterlocked.Update( ref this._initializing, set => set.Remove( securable ) );
    }
}
